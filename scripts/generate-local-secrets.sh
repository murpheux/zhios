#!/usr/bin/env bash
# Creates the git-ignored root .env with random LOCAL-ONLY secrets (for people without
# 1Password; with 1Password use scripts/inject-op-secrets.sh instead). Values are hex
# (URI-safe, MONGO_ROOT_PASSWORD is embedded in MONGODB_URI) and are never printed.
#
# Usage: scripts/generate-local-secrets.sh [output-file]     (default: <repo-root>/.env)
# Refuses to overwrite an existing file — delete it yourself if you really want new secrets
# (existing Mongo volumes keep the OLD root password; see README troubleshooting).
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${1:-${repo_root}/.env}"

command -v openssl >/dev/null 2>&1 || {
  echo "error: openssl not found" >&2
  exit 1
}

if [[ -e "$out" ]]; then
  echo "error: ${out} already exists; refusing to overwrite (remove it first to regenerate)" >&2
  exit 1
fi

rand_hex() {
  openssl rand -hex "$1"
}

umask 077
mongo_password="$(rand_hex 24)"
jwt_secret="$(rand_hex 32)"
internal_jwt_secret="$(rand_hex 32)"
metrics_token="$(rand_hex 24)"

# noclobber: fail rather than race another writer into the same path
set -o noclobber
{
  printf '# zhios local stack secrets. Generated by scripts/generate-local-secrets.sh on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '# LOCAL ONLY. git-ignored. Never commit, never reuse for any shared/prod environment.\n'
  printf 'MONGO_ROOT_USERNAME=zuma_admin\n'
  printf 'MONGO_ROOT_PASSWORD=%s\n' "$mongo_password"
  printf 'JWT_SECRET=%s\n' "$jwt_secret"
  printf 'INTERNAL_JWT_SECRET=%s\n' "$internal_jwt_secret"
  printf 'METRICS_TOKEN=%s\n' "$metrics_token"
} >"$out"
chmod 600 "$out"

echo "wrote ${out} (mode 600; values not shown)"
